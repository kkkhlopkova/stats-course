import numpy as np

def bootci(est_func, x, b=1000, alpha=0.05): # b - количество выборок, которые нужно сгенерировать, alpha - уровень значимости

  x = np.asarray(x)
  n = len(x)

  boot_estimates = np.zeros(b)

  for i in range(b):
      boot_sample = np.random.choice(x, size=n, replace=True)
      cur_est = est_func(boot_sample)
      boot_estimates[i] = cur_est

  low_percentile = (alpha / 2) * 100
  high_percentile = (1 - alpha / 2) * 100

  cint = np.percentile(boot_estimates, [low_percentile, high_percentile])

  return cint

sample = np.random.normal(loc=100, scale=20, size=100)
print(sample[:10])

print(bootci(np.mean, sample))