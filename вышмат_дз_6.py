import numpy as np
import scipy.stats as st

def get_ci(data, alpha=0.05, method=1, bounds=None): # alpha -- желаемая вероятность, что искомое значение не принадлежит интервалу, bounds -- границы размаха генеральной совокупности

  X = np.array(data)
  n, mean, std = len(X), np.mean(X), np.std(X, ddof=1) # ddof обеспечивает исправеленную оценку дисперсии, n-1 вместо n

  # вычисляем margin of error -- расстояние от выборочного среднего до границ доверительного интервала

  if method == 1: #асимптотический метод
    margin = st.norm.ppf(1 - alpha / 2) * (std / np.sqrt(n)) #st.norm -- N(0, 1), ppf -- percent point function, получает координату по x, отсекающую заданную площадь под графиком
  elif method == 2: # метод Стьюдента
    margin = st.t.ppf(1 - alpha / 2, df=n-1) * (std / np.sqrt(n)) # st.t -- распределение Стьюдента, df -- степени свободы, т. е. размер выборки
  elif method == 3: # метод Хора-Хора
    a, b = bounds if bounds else (np.min(X), np.max(X))
    margin = (b - a) * np.sqrt(np.log(2 / alpha) / (2 * n))

  return mean - margin, mean + margin

data = [4, 5, 6, 3, 5, 7, 5, 4, 6, 5]
print("Z-интервал: ", get_ci(data, alpha=0.05, method=1))
print("t-интервал: ", get_ci(data, alpha=0.05, method=2))
print("Хора-Хора:  ", get_ci(data, alpha=0.05, method=3, bounds=(1, 10)))