import numpy as np
import scipy.stats as stats

rng = np.random.default_rng(42)
sample = rng.normal(loc=10, scale=3, size=1000)

print(sample[:10])

# математическое ожидание и медиана

mean_est = np.mean(sample)
median_est = np.median(sample)

print(mean_est)
print(median_est)

# дисперсия и среднеквадратичное отклонение

# смещённые:
var_biased = np.var(sample, ddof=0)
std_biased = np.std(sample, ddof=0)

# несмещённые:
var_unbiased = np.var(sample, ddof=1)
std_unbiased = np.std(sample, ddof=1)

print(std_biased)
print(std_unbiased)

# коэффициенты ассиметрии и избыточного эксцесса

skew_unbiased = stats.skew(sample, bias=False)
kurt_unbiased = stats.kurtosis(sample, bias=False)

print(skew_unbiased)
print(kurt_unbiased)